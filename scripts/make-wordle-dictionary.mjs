import { readFile, writeFile, mkdir } from 'node:fs/promises'
const rules = new Map()
const aff = await readFile('.data/wordle-da-source.aff', 'utf8')
const dic = await readFile('.data/wordle-da-source.dic', 'utf8')
for (const line of aff.split(/\r?\n/)) {
  const [type, flag, strip, addition, condition] = line.trim().split(/\s+/)
  if (type !== 'SFX' || !condition) continue
  const [add, continuation = ''] = addition.split('/')
  const rule = {
    strip: strip === '0' ? '' : strip,
    add: add === '0' ? '' : add,
    flags: continuation.split(','),
    condition: new RegExp(condition + '$'),
  }
  if (!rules.has(flag)) rules.set(flag, [])
  rules.get(flag).push(rule)
}
const words = new Set()
function expand(word, flags, depth = 0) {
  if (flags.includes('6') || flags.includes('36')) return
  if (/^[a-zæøå]{5}$/.test(word) && !flags.includes('8')) words.add(word.toLocaleUpperCase('da-DK'))
  if (depth >= 3) return
  for (const flag of flags)
    for (const rule of rules.get(flag) ?? []) {
      if (!rule.condition.test(word) || !word.endsWith(rule.strip)) continue
      const next = word.slice(0, word.length - rule.strip.length) + rule.add
      if (next.length <= 8) expand(next, rule.flags, depth + 1)
    }
}
for (const line of dic.split(/\r?\n/).slice(1)) {
  const [word, flags = ''] = line.split(/\s/)[0].split('/')
  if (/^[a-zæøå]{1,8}$/.test(word)) expand(word, flags.split(','))
}
await mkdir('server/data', { recursive: true })
await writeFile(
  'server/data/wordle-allowed.json',
  JSON.stringify([...words].sort(), null, 2) + '\n',
)
await writeFile(
  'server/data/wordle-license.txt',
  (await readFile('.data/wordle-da-license.txt', 'utf8')) +
    '\nDerived five-letter list generated by scripts/make-wordle-dictionary.mjs. Distributed under LGPL-2.1.\nSource: https://github.com/wooorm/dictionaries/tree/main/dictionaries/da (Stavekontrolden 2.8.034).\nReproduce by downloading index.dic and index.aff into .data/wordle-da-source.dic and .data/wordle-da-source.aff, and license into .data/wordle-da-license.txt. Download https://www.gnu.org/licenses/old-licenses/lgpl-2.1.txt into .data/wordle-lgpl-2.1.txt, then run the generator.\nThe generator expands suffixes; compounds and proper names are excluded.\n\n' +
    (await readFile('.data/wordle-lgpl-2.1.txt', 'utf8')),
)
console.log(`${words.size} Danish five-letter guesses`)
