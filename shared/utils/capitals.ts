const RADIUS_KM = 25

/** Landekoden, hvis stickeren sidder i (eller tæt ved) landets hovedstad */
export function capitalOf(s: { lat: number; lng: number; countryCode: string }) {
  const c = CAPITALS[s.countryCode.toUpperCase()]
  return c && distanceKm(s, { lat: c[0], lng: c[1] }) <= RADIUS_KM
    ? s.countryCode.toUpperCase()
    : undefined
}
